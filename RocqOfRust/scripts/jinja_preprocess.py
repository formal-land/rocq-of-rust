#!/usr/bin/env python3
"""
Jinja2 preprocessor for Rocq files.

Usage:
    python scripts/jinja_preprocess.py template.v.jinja2 [...]

Each template.v.jinja2 generates a corresponding template.v file.
Templates define their own data using Jinja's {% set %} directive.
"""

import sys
from pathlib import Path

try:
    from jinja2 import Environment, FileSystemLoader, StrictUndefined
except ImportError:
    print("Error: jinja2 is required. Install with: pip install jinja2", file=sys.stderr)
    sys.exit(1)


def render_template(template_path: Path) -> str:
    """Render a single template file."""
    env = Environment(
        loader=FileSystemLoader(template_path.parent),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )

    template = env.get_template(template_path.name)
    return template.render()


def process_template(template_path: Path) -> bool:
    """Process a single template, return True on success."""
    output_path = template_path.with_suffix("")  # Remove .jinja2 suffix

    try:
        rendered = render_template(template_path)
    except Exception as e:
        print(f"Error rendering {template_path}: {e}", file=sys.stderr)
        return False

    # Add generation notice at the top
    notice = f"(* Generated by Jinja from {template_path} - DO NOT EDIT *)\n"
    rendered = notice + rendered

    output_path.write_text(rendered)
    print(f"Generated: {output_path}")
    return True


def main():
    if len(sys.argv) < 2:
        print("Usage: jinja_preprocess.py template.v.jinja2 [...]", file=sys.stderr)
        sys.exit(1)

    templates = [Path(t) for t in sys.argv[1:]]
    errors = 0

    for template in templates:
        if not template.exists():
            print(f"Error: {template} not found", file=sys.stderr)
            errors += 1
            continue

        if not process_template(template):
            errors += 1

    return 1 if errors > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
