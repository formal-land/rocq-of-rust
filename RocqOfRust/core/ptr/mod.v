          let m_minus_one = unsafe { unchecked_sub(m, 1) };
          let mut inverse = INV_TABLE_MOD_16[(x & (INV_TABLE_MOD - 1)) >> 1] as usize;
          let mut mod_gate = INV_TABLE_MOD;
