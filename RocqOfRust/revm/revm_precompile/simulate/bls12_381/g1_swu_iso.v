  Definition sqrt (value : Fq.t) : option Fq.t :=
    let root : Fq.t := {| Fq.repr := {| Uint.value :=
      Modexp.pow_mod value.(Fq.repr).(Uint.value)
        ((Fq.MODULUS.(Uint.value) + 1) / 4) Fq.MODULUS.(Uint.value) |} |} in
    if Fq.eq (Fq.square root) value then Some root else None.

  Definition parity (value : Fq.t) : bool :=
    Z.odd value.(Fq.repr).(Uint.value).

  Module SwuIsoAffine.
    Record t : Set := { x : Fq.t; y : Fq.t }.
  End SwuIsoAffine.

  Definition swu_map_to_curve (element : Fq.t) : option SwuIsoAffine.t :=
    let zeta_u2 := Fq.mul ZETA (Fq.square element) in
    let ta := Fq.add (Fq.square zeta_u2) zeta_u2 in
    let num_x1 := Fq.mul COEFF_B (Fq.add ta Fq.ONE) in
    let div := Fq.mul COEFF_A
      (if Fq.is_zero ta then ZETA else Fq.sub Fq.ZERO ta) in
    let div2 := Fq.square div in
    let div3 := Fq.mul div2 div in
    let num_gx1 := Fq.add
      (Fq.mul (Fq.add (Fq.square num_x1) (Fq.mul COEFF_A div2)) num_x1)
      (Fq.mul COEFF_B div3) in
    match Fq.inverse div3, Fq.inverse div with
    | Some inv_div3, Some inv_div =>
      let gx1 := Fq.mul num_gx1 inv_div3 in
      (* Rust LegendreSymbol::is_qr excludes zero. *)
      let first_root := if Fq.is_zero gx1 then None else sqrt gx1 in
      let candidate :=
        match first_root with
        | Some y1 => Some (num_x1, y1)
        | None =>
          match sqrt (Fq.mul ZETA gx1) with
          | Some y1 => Some
            (Fq.mul zeta_u2 num_x1, Fq.mul (Fq.mul zeta_u2 element) y1)
          | None => None
          end
        end in
      match candidate with
      | Some (num_x, y) => Some
        {| SwuIsoAffine.x := Fq.mul num_x inv_div;
           SwuIsoAffine.y := if Bool.eqb (parity y) (parity element)
             then y else Fq.sub Fq.ZERO y |}
      | None => None
      end
    | _, _ => None
    end.

  (** DensePolynomial coefficients are in increasing degree order. *)
  Fixpoint evaluate (coefficients : list Fq.t) (x : Fq.t) : Fq.t :=
    match coefficients with
    | [] => Fq.ZERO
    | coefficient :: rest => Fq.add coefficient (Fq.mul x (evaluate rest x))
    end.

  (** Arkworks batch_inversion leaves zero entries unchanged. *)
  Definition inverse_or_zero (value : Fq.t) : Fq.t :=
    match Fq.inverse value with Some inverse => inverse | None => Fq.ZERO end.

  Definition isogeny_map_apply (point : SwuIsoAffine.t) : G1Affine.t :=
    let x := point.(SwuIsoAffine.x) in
    {| G1Affine.x := Fq.mul (evaluate x_map_numerator x)
         (inverse_or_zero (evaluate x_map_denominator x));
       G1Affine.y := Fq.mul (Fq.mul (evaluate y_map_numerator x) point.(SwuIsoAffine.y))
         (inverse_or_zero (evaluate y_map_denominator x));
       G1Affine.infinity := false |}.

  (** g1.rs uses the effective cofactor 1 - x, where x is negative. *)
  Definition EFFECTIVE_COFACTOR : Uint.t 256 4 :=
    {| Uint.value := 15132376222941642753 |}.

  Definition clear_cofactor (point : G1Affine.t) : G1Affine.t :=
    G1Projective.into_affine (G1Projective.mul_bigint point EFFECTIVE_COFACTOR).

  Definition map_fp_to_g1 (element : Fq.t) : option G1Affine.t :=
    match swu_map_to_curve element with
    | Some point => Some (clear_cofactor (isogeny_map_apply point))
    | None => None
    end.
End g1_swu_iso.
